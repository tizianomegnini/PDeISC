import { Router } from 'express';
import { requireAuth,allowRoles } from '../middleware/auth.js';
import { listRepairs,createRepair,updateRepair,repairHistory,stats } from '../controllers/repairController.js';
const router=Router();
router.get('/',requireAuth,listRepairs);
router.post('/',requireAuth,allowRoles('cliente'),createRepair);
router.get('/stats',requireAuth,allowRoles('admin'),stats);
router.get('/:id/history',requireAuth,repairHistory);
router.patch('/:id',requireAuth,allowRoles('admin','tecnico'),updateRepair);
export default router;
